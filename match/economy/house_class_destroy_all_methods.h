// Provenance: own-binary-via-Ghidra | YRpp-cross-check
//   Offsets and slots read numerically off the user's retail gamemd.exe v1.001
//   via the local Ghidra CLI at 0x4FC790. Slot 0x2C (whatAmI) and slot 0x16C
//   (receiveDamage) are confirmed by their call shapes at this site; member offsets Health @0x6C, InLimbo @0x81 and
//   TemporalTargetingMe @0x278 are already committed in match/_layout/. Names
//   cross-checked against YRpp.
//
// HouseClass::DestroyAllBuildings @0x4FC790 — walk every techno in the global
// array and destroy the ones this house owns.
//
// Why this header declares a vtable-shaped class rather than using the usual
// function-pointer macro: every indirect virtual call in the tree so far has
// been zero-argument, which the `typedef R (__fastcall* F)(T*)` idiom expresses
// exactly. Slot 0x16C is receiveDamage, which takes seven stack arguments on
// top of ECX=this. __fastcall would claim EDX for the second argument, so that
// idiom cannot emit this call, and vtable_map_techno.md flags the slot as
// "7-arg, complex - defer to a dedicated pass". This is that pass: a flat class
// whose virtuals are declared in slot order up to 0x16C, so `obj->Method(args)`
// compiles to retail's `MOV EDX,[ESI]; ...; CALL [EDX+0x16c]` with the argument
// pushes generated by the compiler in the right order.
//
// The dummy `vt_XXX` slots are declared, never defined and never called; they
// exist only to place the two real virtuals at the right table offsets. The
// class is a call-site shape, not a layout claim about TechnoClass as a whole.
