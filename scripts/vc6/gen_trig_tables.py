# Provenance: own-binary-via-Ghidra (the table shapes and indexing come from the matched readers in
# match/core/trig_table_functions_004cac40.cpp); the formulas below were fitted and then verified
# bit-for-bit against the pinned image, which this file does not embed.
"""Generate the trig / arc / square-root lookup tables as a C++ translation unit.

Retail keeps these five tables as initialised static data. VC6 cannot fold sin() into an initialiser, so the
values come from this script: the tracked source holds only the formulas and the build (build_project.py,
compile_all.py) writes the literal-initialiser .cpp into a gitignored build directory.

Every value is computed in double precision and stored to float by truncation toward zero (the original
tool ran the x87 in round-to-zero mode). The sin/tan reductions reproduce the x87 66-bit pi, which matters
only where an argument is within a few ulp of a multiple of pi/2.

    0x84F084  float[10241]  sin(i * 2pi/8192)                       (one turn of sin plus a quarter, for cos)
    0x859094  float[4097]   asin(-1 + i/2048)
    0x85D0A4  float[4097]   tan(i * 2pi/4096)
    0x8610B4  float[4097]   atan(x_i), x_0 = 0, x_(i+1) = trunc_f32(x_i + step), step = 0x8650B8 (float)
    0x8650BC  uint32[16384] mantissa bits of sqrt(1 + j/8192) (j < 8192) or sqrt(j/4096) (j >= 8192)

Usage: gen_trig_tables.py OUT.cpp         write the translation unit
       gen_trig_tables.py --check         compare with the image at $GAMEMD_BINARY (reads it at run time)
"""
import math
import os
import struct
import sys
from fractions import Fraction

# pi/4 as a 128-bit fraction (a mathematical constant); the x87 keeps the top 66 bits of pi.
PI_QUARTER_128 = 0xC90FDAA22168C234C4C6628B80DC1CD1
HALF_PI_66 = Fraction(PI_QUARTER_128 >> (128 - 66), 1 << 65)
STEP = struct.unpack("<f", struct.pack("<f", 0.024413354694843292))[0]   # the float at 0x8650B8


def f32_bits(x):
    """Bits of the float obtained by truncating the double x toward zero."""
    bits = struct.unpack("<I", struct.pack("<f", x))[0]
    if abs(struct.unpack("<f", struct.pack("<I", bits))[0]) > abs(x):
        bits -= 1
    return bits


def f32(x):
    return struct.unpack("<f", struct.pack("<I", f32_bits(x)))[0]


def reduce(x):
    """(k mod 4, r) with x = k*pi/2 + r, r reduced against the 66-bit pi like fsin/fptan."""
    k = round(x / (math.pi / 2))
    return k % 4, float(Fraction(x) - k * HALF_PI_66)


def x87_sin(x):
    k, r = reduce(x)
    return (math.sin(r), math.cos(r), -math.sin(r), -math.cos(r))[k]


def x87_tan(x):
    k, r = reduce(x)
    return math.tan(r) if k % 2 == 0 else -1.0 / math.tan(r)


def sin_table():
    return [f32_bits(x87_sin(i * 2 * math.pi / 8192)) for i in range(10241)]


def asin_table():
    return [f32_bits(math.asin(max(-1.0, min(1.0, -1 + i / 2048)))) for i in range(4097)]


def tan_table():
    return [f32_bits(x87_tan(i * 2 * math.pi / 4096)) for i in range(4097)]


def atan_table():
    out, x = [], 0.0
    for _ in range(4097):
        out.append(f32_bits(math.atan(x)))
        x = f32(x + STEP)
    return out


def sqrt_table():
    return [f32_bits(math.sqrt(1 + j / 8192 if j < 8192 else j / 4096)) - 0x3F800000 for j in range(16384)]


# name, address, element type, const, builder
TABLES = [
    ("DAT_0084F084", 0x84F084, "float", False, sin_table),
    ("DAT_00859094", 0x859094, "float", False, asin_table),
    ("DAT_0085D0A4", 0x85D0A4, "float", False, tan_table),
    ("DAT_008610B4", 0x8610B4, "float", True, atan_table),
    ("DAT_008650BC", 0x8650BC, "unsigned int", True, sqrt_table),
]


def spell_float(bits):
    value = struct.unpack("<f", struct.pack("<I", bits))[0]
    for precision in range(1, 10):
        text = f"{value:.{precision}g}"
        if struct.unpack("<I", struct.pack("<f", float(text)))[0] == bits:
            break
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "f"


def render():
    lines = ["// Generated by scripts/vc6/gen_trig_tables.py; do not edit or commit.",
             "// Provenance: own-binary-via-Ghidra"]
    for name, va, ctype, const, build in TABLES:
        bits = build()
        items = [spell_float(b) if ctype == "float" else f"0x{b:X}" for b in bits]
        lines += [f"// GLOBAL: GAMEMD 0x{va:X}",
                  f"extern {'const ' if const else ''}{ctype} {name}[{len(items)}] = {{"]
        lines += ["    " + ", ".join(items[i:i + 8]) + "," for i in range(0, len(items), 8)]
        lines += ["};", ""]
    return "\n".join(lines)


def check():
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import hybrid
    import pindata
    retail = hybrid.Retail(pindata.retail_path())
    bad = 0
    for name, va, _, _, build in TABLES:
        want = build()
        got = struct.unpack(f"<{len(want)}I", bytes(retail.fill(va, 4 * len(want))))
        diff = [i for i, (a, b) in enumerate(zip(want, got)) if a != b]
        print(f"{name} 0x{va:X}: {len(want)} entries, {len(diff)} differ {diff[:8]}")
        bad += len(diff)
    return 1 if bad else 0


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        sys.exit(check())
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with open(sys.argv[1], "w", newline="\n") as out:
        out.write(render())
