#!/usr/bin/env python3
"""verify_safe.py: scripts/vc6/verify_all.py without shared /tmp/va_<name>.obj files.

verify_all.py compiles every TU to /tmp/va_<basename>.obj. Two overlapping runs
(or two TUs with the same basename in different directories) overwrite each
other's objects and one run then verifies the other's bytes. This wrapper keeps
the verdict logic (it imports verify_all.verify from the tree) but

  * compiles into a private mkdtemp() directory, one subdirectory per TU
    (so same-basename TUs cannot collide either), removed on exit;
  * can restrict to --tu / --tus-from FILE / --shard I/N;
  * runs TUs in parallel (--jobs);
  * prints the same lines and the same final summary, exit 1 on regression or
    compile failure.

The wrapper never edits the tree. The equivalent in-place fix for verify_all.py
itself is proposed in proposed_patches/verify_all_tmpdir.patch.

    verify_safe.py [--tree T] [--manifest M] [--md OUT] [--tu a.cpp]... [--tus-from F]
                   [--shard I/N] [--jobs N] [--keep]
"""
import argparse
import concurrent.futures as cf
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import landlib as L  # noqa: E402


def load_va(tree):
    # verify_all imports its siblings (changed_tus) by bare name.
    vc6 = os.path.join(tree, "scripts/vc6")
    if vc6 not in sys.path:
        sys.path.insert(0, vc6)
    spec = importlib.util.spec_from_file_location("va_tree", os.path.join(tree, "scripts/vc6/verify_all.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tree", default=os.getcwd())
    ap.add_argument("--manifest")
    ap.add_argument("--md")
    ap.add_argument("--tu", action="append", default=[])
    ap.add_argument("--tus-from")
    ap.add_argument("--shard")
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--keep", action="store_true", help="keep the temp dir (path printed)")
    a = ap.parse_args(argv)
    tree = os.path.abspath(a.tree)
    va = load_va(tree)
    manifest = a.manifest or os.path.join(tree, "scripts/data/match_manifest.json")
    man = json.load(open(manifest))
    by_tu = {}
    for e in man:
        by_tu.setdefault(e["tu"], []).append(e)
    tus = sorted(by_tu)
    want = set(a.tu)
    if a.tus_from:
        want |= {x.strip() for x in open(a.tus_from) if x.strip()}
    if want:
        tus = [t for t in tus if t in want]
    if a.shard:
        i, n = map(int, a.shard.split("/"))
        tus = [t for k, t in enumerate(tus) if k % n == i % n]
    env = L.toolenv()
    os.environ["GAMEMD_BINARY"] = env["GAMEMD_BINARY"]
    work = tempfile.mkdtemp(prefix="verify_safe_")
    if a.keep:
        print("temp dir:", work)

    def one(tu):
        d = os.path.join(tree, os.path.dirname(tu))
        f = os.path.basename(tu)
        sub = tempfile.mkdtemp(dir=work)
        obj = os.path.join(sub, os.path.splitext(f)[0] + ".obj")
        with open(os.devnull, "wb") as dn:
            c = subprocess.run(["bash", os.path.join(tree, "scripts/vc6/vc6cl.sh"), "/Fo" + obj, f], cwd=d,
                               stdout=dn, stderr=dn, env=env)
        if c.returncode != 0 or not os.path.exists(obj):
            return tu, None, 0, 0, []
        m = p = 0
        bad = []
        for e in by_tu[tu]:
            if e.get("status") == "matched":
                ok, pc = va.verify(obj, e["sym"], e["addr"], e["len"])
                if ok:
                    m += 1
                else:
                    bad.append("%s -> %s" % (e["name"], pc))
            else:
                p += 1
        shutil.rmtree(sub, ignore_errors=True)
        return tu, True, m, p, bad

    tot_m = tot_p = regr = 0
    fail = False
    md = ["# Match-% Dashboard", "",
          "Auto-generated by `verify_safe.py` from `scripts/data/match_manifest.json`.",
          "", "| TU | matched | partial | status |", "|----|--------:|--------:|--------|"]
    try:
        with cf.ThreadPoolExecutor(a.jobs) as ex:
            for tu, ok, m, p, bad in ex.map(one, tus):
                if not ok:
                    print("COMPILE FAIL  %s" % tu)
                    fail = True
                    md.append("| `%s` | — | — | **COMPILE FAIL** |" % tu)
                    continue
                for b in bad:
                    print("  REGRESSED %s::%s" % (tu, b))
                regr += len(bad)
                tot_m += m
                tot_p += p
                st = "OK" if not bad else "**REGRESSED: " + "; ".join(bad) + "**"
                print("  %-46s matched %d  partial %d  %s" % (tu, m, p, st if bad else ""))
                md.append("| `%s` | %d | %d | %s |" % (tu, m, p, st))
    finally:
        if not a.keep:
            shutil.rmtree(work, ignore_errors=True)
    md.insert(5, "| **TOTAL** | **%d** | **%d** | %s |" % (
        tot_m, tot_p, "**%d REGRESSED**" % regr if regr else "all green"))
    print("\n=== %d matched (100%%), %d documented partials, %d regressed, across %d TUs ===" % (
        tot_m, tot_p, regr, len(tus)))
    if a.md:
        open(a.md, "w").write("\n".join(md) + "\n")
    return 1 if (fail or regr) else 0


if __name__ == "__main__":
    sys.exit(main())
